const filePath = path.resolve('./client/src/i18n/pages/LectureBuilder.ts');
let content = fs.readFileSync(filePath, 'utf-8');

// For each language, find the closing `});` of that language block and insert before it
const langs = ['ko', 'en', 'zh', 'ja', 'vi', 'th', 'id', 'ms', 'es', 'fr', 'de', 'pt', 'ru', 'ar', 'hi', 'it', 'nl', 'pl', 'sv', 'tr'];

for (const lang of langs) {
  const trans = translations[lang];
  if (!trans) continue;
  
  // Build the entries string
  const entries = Object.entries(trans)
    .map(([key, val]) => `  "${key}": "${val.replace(/"/g, '\\"')}",`)
    .join('\n');
  
  // Find the pattern: registerTranslations("lang", { ... }); and insert before the last });
  // Strategy: find the last occurrence of the key pattern for this language block
  // Use a unique key from the last entry of each block to find insertion point
  const lastKeyPattern = `"lectureBuilder.hardcoded.restoreVersionConfirm"`;
  
  // Find all occurrences of registerTranslations for this lang
  const regStart = `registerTranslations("${lang}", {`;
  const startIdx = content.indexOf(regStart);
  if (startIdx === -1) {
    console.log(`Warning: Could not find registerTranslations for "${lang}"`);
    continue;
  }
  
  // Find the closing }); after this start
  let braceCount = 0;
  let foundOpen = false;
  let closeIdx = -1;
  for (let i = startIdx; i < content.length; i++) {
    if (content[i] === '{') {
      braceCount++;
      foundOpen = true;
    } else if (content[i] === '}') {
      braceCount--;
      if (foundOpen && braceCount === 0) {
        closeIdx = i;
        break;
      }
    }
  }
  
  if (closeIdx === -1) {
    console.log(`Warning: Could not find closing brace for "${lang}"`);
    continue;
  }
  
  // Insert entries before the closing }
  content = content.slice(0, closeIdx) + entries + '\n' + content.slice(closeIdx);
}

fs.writeFileSync(filePath, content, 'utf-8');
