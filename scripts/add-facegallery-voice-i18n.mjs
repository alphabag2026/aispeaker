// The file has blocks like:
// registerTranslations("ko", {
//   "fg.select_this_face": "이 얼굴 선택하기",
// });
// We need to add new keys before the closing });

const langOrder = ['ko','en','zh','ja','vi','th','es','fr','de','pt','ru','ar','hi','id','ms','tr','it','nl','pl','sv'];

for (const lang of langOrder) {
  const keys = newKeys[lang];
  if (!keys) continue;
  
  // Find the closing }); after the last key of this language block
  // Pattern: "fg.select_this_face": "...",\n});
  const lastKeyLine = content.indexOf(`"fg.select_this_face"`, content.indexOf(`registerTranslations("${lang}"`));
  if (lastKeyLine === -1) {
    console.log(`❌ ${lang}: could not find select_this_face key`);
    continue;
  }
  
  // Find the end of that line
  const lineEnd = content.indexOf('\n', lastKeyLine);
  // Find the }); after it
  const closingBrace = content.indexOf('});', lineEnd);
  
  if (closingBrace === -1) {
    console.log(`❌ ${lang}: could not find closing });`);
    continue;
  }
  
  // Insert new keys before });
  const keyEntries = Object.entries(keys).map(([k, v]) => `  "${k}": "${v}",`).join('\n');
  content = content.slice(0, closingBrace) + keyEntries + '\n' + content.slice(closingBrace);
  console.log(`✅ ${lang}: ${Object.keys(keys).length} keys added`);
}

fs.writeFileSync(filePath, content);
console.log('\n✅ Done! All FaceGallery voice management i18n keys added.');
